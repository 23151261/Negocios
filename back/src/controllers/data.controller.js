            const metadata = productMeta[product.id] || {};
            const strategy = String(metadata.strategy || 'PUSH').toUpperCase();
            const minStock = Number(metadata.minStock);
            if (metadata.minStock == null || !Number.isSafeInteger(minStock) || minStock < 1) return [];
            if (Number(product.stock) > minStock) return [];
            const providerId = Number(metadata.providerId) || getDefaultProviderId(product.category);
            const provider = providers.find(item => Number(item.id) === providerId);
            const activeOrder = orders.find(item =>
                Number(item.productId) === Number(product.id)
                && ['Reposición', 'Suministro'].includes(item.type)
                && ['pendiente', 'en proceso'].includes(String(item.status || '').toLowerCase())
            );
