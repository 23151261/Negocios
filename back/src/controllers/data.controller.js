function toDate(value) {
    if (!value) return new Date();
    if (value instanceof Date) {
        return isNaN(value.getTime()) ? new Date() : value;
    }
    if (typeof value === 'string') {
        const match = value.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})/);
        if (match) {
            const d = new Date(Number(match[3]), Number(match[2]) - 1, Number(match[1]));
            if (!isNaN(d.getTime())) return d;
        }
    }
    const parsed = new Date(value);
    return isNaN(parsed.getTime()) ? new Date() : parsed;
}

function toInteractionType(value) {
    const normalized = String(value || 'nota').trim().toLowerCase();
    const aliases = {
        registro: 'nota',
        llamada: 'llamada',
        correo: 'correo',
        reunion: 'reunion',
        'reunión': 'reunion',
        nota: 'nota',
        compra: 'compra',
        pedido: 'compra',
        seguimiento: 'nota'
    };
    return aliases[normalized] || 'nota';
}

function parseAddress(value) {
    if (!value || typeof value !== 'string') return value;
    try {
        return JSON.parse(value);
    } catch (_) {
        return value;
    }
}

function parseJsonValue(value, fallback) {
    if (typeof value === 'string') return JSON.parse(value);
    return value || fallback;
}

function getDefaultProviderId(category) {
    if (category === 'Pizzas') return 2;
    if (category === 'Pescados') return 3;
    if (category === 'Bebidas') return 5;
    if (category === 'Ensaladas') return 4;
    return 1;
}

async function ensureLowStockOrders(connection) {
    const [products] = await connection.query('SELECT id, name, category, stock FROM productos ORDER BY id');
    const [metaRows] = await connection.query("SELECT data_value FROM app_data WHERE data_key = 'scm_product_meta'");
    const [orderRows] = await connection.query("SELECT data_value FROM app_data WHERE data_key = 'scm_orders'");
    const [providerRows] = await connection.query("SELECT data_value FROM app_data WHERE data_key = 'scm_providers'");
    const productMeta = parseJsonValue(metaRows[0]?.data_value, {});
    const orders = parseJsonValue(orderRows[0]?.data_value, []);
    const providers = parseJsonValue(providerRows[0]?.data_value, []);
    const activeStatuses = new Set(['pendiente', 'en proceso']);
    const productById = new Map(products.map(product => [Number(product.id), product]));
    let nextId = Math.max(Date.now(), ...orders.map(order => Number(order.id) || 0)) + 1;
    let nextFolio = orders.reduce((max, order) => {
        const match = String(order.folio || '').match(/^PC-(\d+)$/i);
        return match ? Math.max(max, Number(match[1])) : max;
    }, 0) + 1;
    const createdOrders = [];
    let cancelledStaleOrders = false;
    let clearedCancellationBlocks = false;

    for (const order of orders) {
        const metadata = productMeta[order.productId] || {};
        const product = productById.get(Number(order.productId));
        const minStock = Number(metadata.minStock);
        if (order.retrySuppressedUntilStockRecovers
            && product
            && metadata.minStock != null
            && Number.isSafeInteger(minStock)
            && Number(product.stock) > minStock) {
            delete order.retrySuppressedUntilStockRecovers;
            clearedCancellationBlocks = true;
        }
        const isActive = activeStatuses.has(String(order.status || '').toLowerCase());
        if (!order.autoGenerated || !isActive) continue;

        if (String(metadata.strategy || 'PUSH').toUpperCase() !== 'PUSH') {
            order.status = 'Cancelado';
            order.notes = `${order.notes || ''}${order.notes ? ' ' : ''}Cancelado: estrategia PULL requiere pedido manual.`;
            cancelledStaleOrders = true;
            continue;
        }
        if (metadata.minStock == null || !Number.isSafeInteger(minStock) || minStock < 1) {
            order.status = 'Cancelado';
            order.notes = `${order.notes || ''}${order.notes ? ' ' : ''}Cancelado: el producto no tiene un stock mínimo configurado.`;
            cancelledStaleOrders = true;
            continue;
        }
        if (!product || Number(product.stock) > minStock) {
            order.status = 'Cancelado';
            order.notes = `${order.notes || ''}${order.notes ? ' ' : ''}Cancelado: el stock está por encima del mínimo configurado.`;
            cancelledStaleOrders = true;
            continue;
        }
        if (Number(order.quantity) !== minStock) {
            order.quantity = minStock;
            order.notes = `Pedido automático: stock ${Number(product.stock)} (mínimo ${minStock}).`;
            cancelledStaleOrders = true;
        }
    }

    for (const product of products) {
        const metadata = productMeta[product.id] || {};
        const strategy = String(metadata.strategy || 'PUSH').toUpperCase();
        const minStock = Number(metadata.minStock);
        if (strategy !== 'PUSH' || metadata.minStock == null || !Number.isSafeInteger(minStock) || minStock < 1 || Number(product.stock) > minStock) continue;
        if (orders.some(order => Number(order.productId) === Number(product.id) && order.retrySuppressedUntilStockRecovers)) continue;

        const activeOrder = orders.find(order =>
            Number(order.productId) === Number(product.id)
            && ['Reposición', 'Suministro'].includes(order.type)
            && activeStatuses.has(String(order.status || '').toLowerCase())
        );
        if (activeOrder) continue;

        const providerId = Number(metadata.providerId) || getDefaultProviderId(product.category);
        const provider = providers.find(item => Number(item.id) === providerId);
        if (!provider) continue;

        const now = new Date();
        const order = {
            id: nextId++,
            folio: `PC-${String(nextFolio++).padStart(3, '0')}`,
            date: now.toLocaleDateString('es-MX'),
            productId: Number(product.id),
            quantity: minStock,
            type: 'Reposición',
            status: 'Pendiente',
            providerId,
            notes: `Pedido automático: stock ${Number(product.stock)} (mínimo ${minStock}).`,
            autoGenerated: true
        };
        orders.unshift(order);
        createdOrders.push(order);
    }

    if (createdOrders.length > 0 || cancelledStaleOrders || clearedCancellationBlocks) {
        await connection.query(
            'INSERT INTO app_data (data_key, data_value) VALUES (?, ?) ON DUPLICATE KEY UPDATE data_value = VALUES(data_value)',
            ['scm_orders', JSON.stringify(orders)]
        );
    }

    return createdOrders;
}

