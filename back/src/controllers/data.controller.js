            id: row.id,
            pedidoId: row.pedido_id,
            folio: row.folio,
            rfc: row.rfc,
            razonSocial: row.razon_social,
            regimen: row.regimen,
            cp: row.cp,
            uso: row.uso_cfdi,
            fecha: row.created_at
